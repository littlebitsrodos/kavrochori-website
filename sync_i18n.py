class Isolator(HTMLParser):
    """Drop elements whose lang is a known locale other than `keep`.

    Void tags do not change the skip depth: an <img> inside a skipped
    block has no end tag, and counting it would swallow the rest of the page.
    """

    def __init__(self, keep: str):
        super().__init__(convert_charrefs=False)
        self.keep = keep
        self.skip_depth = 0
        self.out = []

    def _skip_start(self, tag: str, attrs) -> bool:
        if self.skip_depth:
            if tag not in VOID_TAGS:
                self.skip_depth += 1
            return True
        lang = dict(attrs).get("lang")
        if lang in LANGS and lang != self.keep:
            if tag not in VOID_TAGS:
                self.skip_depth = 1
            return True
        return False

    def handle_starttag(self, tag, attrs):
        if self._skip_start(tag, attrs):
            return
        self.out.append(self.get_starttag_text())

    def handle_startendtag(self, tag, attrs):
        if self.skip_depth:
            return
        lang = dict(attrs).get("lang")
        if lang in LANGS and lang != self.keep:
            return
        self.out.append(self.get_starttag_text())

    def handle_endtag(self, tag):
        if self.skip_depth:
            self.skip_depth -= 1
            return
        self.out.append(f"</{tag}>")

    def handle_data(self, data):
        if not self.skip_depth:
            self.out.append(data)

    def handle_comment(self, data):
        if not self.skip_depth:
            self.out.append(f"<!--{data}-->")

    def handle_entityref(self, name):
        if not self.skip_depth:
            self.out.append(f"&{name};")

    def handle_charref(self, name):
        if not self.skip_depth:
            self.out.append(f"&#{name};")

    def handle_decl(self, decl):
        if not self.skip_depth:
            self.out.append(f"<!{decl}>")

    def handle_pi(self, data):
        if not self.skip_depth:
            self.out.append(f"<?{data}>")

    def unknown_decl(self, data):
        if not self.skip_depth:
            self.out.append(f"<![{data}]>")


class LangCensus(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=False)
        self.found = []

    def handle_starttag(self, tag, attrs):
        lang = dict(attrs).get("lang")
        if lang:
            self.found.append((tag, lang))

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)


def normalize_asset_paths(html: str) -> str:
    """Convert relative 'images/...' refs to root-absolute '/images/...'."""
    html = re.sub(
        r'((?:src|href|data-full|data-thumb|srcset)=")images/',
        r"\1/images/",
        html,
    )
    html = re.sub(r"(,\s*)images/", r"\1/images/", html)
    html = re.sub(r"(url\(['\"]?)images/", r"\1/images/", html)
    return html


def _swap_meta(html: str, attr: str, value: str, new_content: str) -> str:
    pattern = rf'(<meta\s+{attr}="{re.escape(value)}"\s+content=")[^"]*(")'
    return re.sub(pattern, lambda m: f"{m.group(1)}{new_content}{m.group(2)}", html)


def isolate_language(html: str, lang: str) -> str:
    parser = Isolator(lang)
    parser.feed(html)
    parser.close()
    if parser.skip_depth != 0:
        raise SystemExit(f"{lang}: language filter ended inside a skipped element")
    return "".join(parser.out)


def set_hero_alt(html: str, alt: str) -> str:
    pattern = r'(<img src="/images/fouk-2026-07/dji-0128-800.webp" alt=")[^"]*(")'
    updated, n = re.subn(pattern, lambda m: f"{m.group(1)}{alt}{m.group(2)}", html, count=1)
    if n != 1:
        raise SystemExit("hero image alt marker not found")
    return updated


def update_jsonld(html: str, lang: str) -> str:
    schema = SCHEMA[lang]
    match = re.search(
        r'(<script type="application/ld\+json">)(.*?)(</script>)',
        html,
        re.S,
    )
    if not match:
        raise SystemExit("JSON-LD block not found")
    data = json.loads(match.group(2))
    data["url"] = schema["url"]
    data["name"] = schema["name"]
    data["description"] = schema["description"]
    data["inLanguage"] = lang
    data["offers"] = {
        "@type": "Offer",
        "price": OFFER_PRICE,
        "priceCurrency": "EUR",
        "availability": "https://schema.org/InStock",
        "businessFunction": "https://schema.org/Sell",
        "url": schema["url"],
    }
    house = data.get("mainEntity") or {}
    house["name"] = schema["house"]
    address = house.get("address") or {}
    address["addressLocality"] = schema["locality"]
    address["addressRegion"] = schema["region"]
    house["address"] = address
    data["mainEntity"] = house
    dumped = json.dumps(data, ensure_ascii=False, indent=2).replace("<", "\\u003c")
    return html[: match.start()] + match.group(1) + "\n" + dumped + "\n" + match.group(3) + html[match.end() :]


def generate_variant(master_html: str, lang: str, cfg: dict | None) -> str:
    html = master_html.replace(SOURCE_NOTE + "\n", "").replace(SOURCE_NOTE, "")
    if GENERATED_NOTE not in html:
        html = html.replace("<!DOCTYPE html>\n", "<!DOCTYPE html>\n" + GENERATED_NOTE + "\n", 1)

    html = re.sub(
        r'<meta name="robots" content="[^"]*">',
        '<meta name="robots" content="index, follow">',
        html,
        count=1,
    )

    if lang == "he":
        html = html.replace('<html lang="el">', '<html lang="he" dir="rtl">', 1)
    elif lang != "el":
        html = html.replace('<html lang="el">', f'<html lang="{lang}">', 1)
    html = html.replace("<body>", f'<body class="{lang}">', 1)

    if cfg:
        locale = cfg["locale"]
        html = html.replace(
            '<link rel="canonical" href="https://kavrochori.gr/">',
            f'<link rel="canonical" href="https://kavrochori.gr/{lang}/">',
        )
        html = html.replace(
            '<meta property="og:url" content="https://kavrochori.gr/">',
            f'<meta property="og:url" content="https://kavrochori.gr/{lang}/">',
        )
        html = html.replace(
            '<meta property="og:locale" content="el_GR">',
            f'<meta property="og:locale" content="{locale}">',
        )
        html = re.sub(r"<title>[^<]*</title>", f"<title>{cfg['title']}</title>", html, count=1)
        html = _swap_meta(html, "name", "description", cfg["description"])
        html = _swap_meta(html, "property", "og:title", cfg["og_title"])
        html = _swap_meta(html, "property", "og:description", cfg["og_description"])
        html = _swap_meta(html, "property", "og:image:alt", cfg["og_image_alt"])
        html = _swap_meta(html, "name", "twitter:title", cfg["og_title"])
        html = _swap_meta(html, "name", "twitter:description", cfg["og_description"])
        html = html.replace(
            '<button class="active" onclick="setLang(\'el\', event)">',
            '<button onclick="setLang(\'el\', event)">',
        )
        html = html.replace(
            f"<button onclick=\"setLang('{lang}', event)\">",
            f"<button class=\"active\" onclick=\"setLang('{lang}', event)\">",
        )

    html = set_hero_alt(html, HERO_ALT[lang])
    html = update_jsonld(html, lang)
    html = isolate_language(html, lang)
    # Dropping the other languages leaves their indentation as trailing spaces.
    html = re.sub(r"[ \t]+(?=\n)", "", html)
    assert_page(html, lang)
    return html


def assert_page(html: str, lang: str) -> None:
    census = LangCensus()
    census.feed(html)
    census.close()
    h1 = [tag for tag, found in census.found if tag == "h1"]
    if len(h1) != 1:
        raise SystemExit(f"{lang}: expected 1 h1, found {len(h1)}")
    foreign = [(tag, found) for tag, found in census.found if found != lang]
    if foreign:
        sample = ", ".join(f"{tag}:{found}" for tag, found in foreign[:8])
        raise SystemExit(f"{lang}: elements left in another language ({sample})")
    if f'lang="{lang}"' not in html.split("<h1", 1)[1].split(">", 1)[0]:
        raise SystemExit(f"{lang}: h1 is not marked {lang}")
    if 'hreflang="en-IL"' in html or "wss://stream.binance.com" in html:
        raise SystemExit(f"{lang}: removed signal came back (en-IL or Binance WebSocket)")
    if HERO_ALT[lang] not in html:
        raise SystemExit(f"{lang}: hero alt missing")
    if '"price": "610000"' not in html or '"priceCurrency": "EUR"' not in html:
        raise SystemExit(f"{lang}: Offer price missing from JSON-LD")
    if SCHEMA[lang]["url"] not in html:
        raise SystemExit(f"{lang}: canonical URL missing from JSON-LD")
    block = re.search(r'<script type="application/ld\+json">(.*?)</script>', html, re.S)
    data = json.loads(block.group(1))
    if data.get("url") != SCHEMA[lang]["url"] or data.get("name") != SCHEMA[lang]["name"]:
        raise SystemExit(f"{lang}: JSON-LD url/name mismatch")
    if data["offers"]["price"] != OFFER_PRICE or data["offers"]["priceCurrency"] != "EUR":
        raise SystemExit(f"{lang}: JSON-LD offer mismatch")


def bump_sitemap_lastmod() -> None:
    if not os.path.isfile(SITEMAP):
        return
    today = datetime.date.today().isoformat()
    with open(SITEMAP, encoding="utf-8") as f:
        xml = f.read()
    if "en-IL" in xml:
        raise SystemExit("sitemap still lists hreflang en-IL")
    new_xml = re.sub(
        r"<lastmod>\d{4}-\d{2}-\d{2}</lastmod>",
        f"<lastmod>{today}</lastmod>",
        xml,
    )
    if new_xml != xml:
        with open(SITEMAP, "w", encoding="utf-8") as f:
            f.write(new_xml)
        print(f"Bumped <lastmod> to {today} in {SITEMAP}")


def main() -> int:
    if not os.path.isfile(MASTER):
        print(f"ERROR: master not found at {MASTER}", file=sys.stderr)
        return 1

    with open(MASTER, encoding="utf-8") as f:
        master = f.read()

    if '<h1 lang="el">' not in master or '<h1 lang="fr">' not in master:
        print("ERROR: index.source.html is missing translations. Do not point this script at a published page.", file=sys.stderr)
        return 1

    normalized = normalize_asset_paths(master)
    if normalized != master:
        with open(MASTER, "w", encoding="utf-8") as f:
            f.write(normalized)
        print(f"Normalized asset paths in {MASTER}")
        master = normalized

    pages = [("el", None, os.path.join(ROOT, "index.html"))]
    for lang, cfg in VARIANTS.items():
        pages.append((lang, cfg, os.path.join(ROOT, lang, "index.html")))

    for lang, cfg, outpath in pages:
        os.makedirs(os.path.dirname(outpath), exist_ok=True)
        variant = generate_variant(master, lang, cfg)
        with open(outpath, "w", encoding="utf-8") as f:
            f.write(variant)
        print(f"Wrote {outpath}")

    bump_sitemap_lastmod()
    return 0


if __name__ == "__main__":
    sys.exit(main())
